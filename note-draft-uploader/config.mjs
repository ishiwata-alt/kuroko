  // --------------------------------------------------------------------------
  //   headless=false でブラウザを表示して実行します（動作が見えて安心・確実）。
  headless: process.env.NOTE_HEADLESS === "1",

  // 1本ごとの待ち時間(ms)。連続作成でnoteに負荷をかけないための間隔。
  delayBetweenMs: 6000,

  // 貼り付け後、自動保存(下書き)を待つ時間(ms)
  autosaveWaitMs: 5000,

